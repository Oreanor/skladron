/**
 * Число от 0 до 1 по трём числам — без жребия: одно и то же место и номер
 * всегда дают одно и то же. Отрисовке нельзя брать случайные числа боя
 * (бой у защитника и на сервере обязан совпадать), а Math.random давал бы
 * разную картинку в каждом кадре.
 */
export function hash(x: number, y = 0, k = 0) {
  const v = Math.sin(x * 12.9898 + y * 78.233 + k * 37.719) * 43758.5453;
  return v - Math.floor(v);
}
