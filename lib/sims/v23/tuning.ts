/**
 * Версия правил боя. Растёт каждый раз, когда шаг симуляции начинает
 * считать иначе: налёты, отложенные под старой версией, сервер отвергает —
 * иначе повтор у нападавшего разошёлся бы с тем, что видел защитник.
 * Четвёртая — ракетницы и невидимка, пятая — размагничивание ловушек и
 * надбавка к скорости закрученному строю, шестая — разогнанная ракета,
 * седьмая — шары заграждения, восьмая — столкновение с ними по касанию,
 * девятая — темп стрельбы растёт с уровнем, десятая — шары висят шире,
 * одиннадцатая — начинка «обдув», двенадцатая — обдув сильнее,
 * тринадцатая — взрывчатка забирает квадрат в две клетки, четырнадцатая —
 * она же забирает крест из пяти, пятнадцатая — турбо и гуще капель,
 * шестнадцатая — сбитая взрывчатка рвётся крестом, а дроны не исчезают,
 * семнадцатая — направление спирали задаёт нападающий, а не случай,
 * восемнадцатая — ракетница бьёт не дальше зенитки, девятнадцатая — ракета
 * держит одну цель и, потеряв её, не ищет другую, двадцатая — снаряд
 * зенитки медленнее ракеты, двадцать первая — он неуправляемый и летит с
 * упреждением, двадцать вторая — зенитка стреляет, только довернув ствол,
 * двадцать третья — у огнетушителя нет бака, он на водопроводе.
 */
